"""Generate only missing 0041 Settings glyphs from an installed Noto Sans SC.

Requires Pillow at generation time only. Native rendering retains the original
ROM callbacks, font metadata, glyphs and kerning, and uses this small fallback
only when a requested character is absent. No device access or actual codes.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

from PIL import Image, ImageDraw, ImageFont, __version__ as pillow_version

BASE = 0x9ffff000
ROM_SHA = '972db4c136c7ed9e24a83c07c1a7fd62040ca018b08ca285216d26b1fee3c6b9'
TEXTS = ['设备码', '重新生成', '返回主菜单', '读取失败', '保存失败', '结果待确认', '生成中']
REQUIRED = sorted(set(map(ord, ''.join(TEXTS) + '0123456789')))


def decode(rom, address):
    def read(fmt, at):
        offset = at - BASE
        size = struct.calcsize(fmt)
        assert 0 <= offset <= len(rom) - size
        return struct.unpack_from(fmt, rom, offset)
    wrapper = read('<9I', address)
    height, baseline = (25, 4) if address == 0xa02548d4 else (20, 2)
    assert wrapper[:6] == (0xa00e4864, 0xa00e45aa, 0, height, baseline, 0x1fe00)
    bitmap, glyphs, cmaps, kern, packed = read('<5I', wrapper[6])
    assert (packed >> 25) & 15 == 4 and packed >> 30 == 0
    points = set()
    for index in range((packed >> 16) & 511):
        first, length, first_gid, unicodes, offsets, count, kind = read('<IHHIIHB', cmaps + index * 20)
        if kind in (0, 2):
            pairs = [(delta, read('<B', offsets + delta)[0] if kind == 0 else delta) for delta in range(length)]
            pairs = [(delta, first_gid + gid) for delta, gid in pairs if kind == 2 or delta == 0 or gid]
        else:
            assert kind in (1, 3)
            pairs = [(read('<H', unicodes + i * 2)[0], first_gid + (read('<H', offsets + i * 2)[0] if kind == 1 else i)) for i in range(count)]
        for delta, gid in pairs:
            word, width, height, x, y = read('<IBBbb', glyphs + gid * 8)
            if gid and width and height:
                points.add(first + delta)
    return wrapper, points


def array(name, ctype, values):
    lines = [f'static const {ctype} {name}[] = {{']
    for at in range(0, len(values), 20):
        lines.append('    ' + ','.join(str(v) for v in values[at:at + 20]) + ',')
    return '\n'.join(lines) + '\n};\n'


def generate(rom, font_path):
    output = ['// Generated by generate-device-code-font-0041.py; do not edit.\n']
    report = {}
    for name, address, weight in [('Normal', 0xa025488c, 400), ('Selected', 0xa055fb7c, 700), ('Title', 0xa02548d4, 400)]:
        wrapper, existing = decode(rom, address)
        required = set(map(ord, '设备码')) if name == 'Title' else set(REQUIRED)
        missing = sorted(required - existing)
        size, baseline = wrapper[3:5]
        face = ImageFont.truetype(str(font_path), size)
        face.set_variation_by_axes([weight])
        pixels, records = bytearray(), [(0, 0, 0, 0, 0)]
        glyph_report = []
        for cp in missing:
            text = chr(cp)
            left, top, right, bottom = face.getbbox(text, anchor='ls')
            width, height = right - left, bottom - top
            assert 0 < width <= 32 and 0 < height <= size + 2 and -128 <= left <= 127 and -128 <= -bottom <= 127
            image = Image.new('L', (width, height))
            ImageDraw.Draw(image).text((-left, -top), text, font=face, fill=255, anchor='ls')
            alpha = [(value * 15 + 127) // 255 for value in image.tobytes()]
            assert max(alpha) > 0
            advance = round(face.getlength(text) * 16)
            records.append((len(pixels) | (advance << 20), width, height, left, -bottom))
            for at in range(0, len(alpha), 2):
                pixels.append((alpha[at] << 4) | (alpha[at + 1] if at + 1 < len(alpha) else 0))
            glyph_report.append(dict(codepoint=cp, character=text, width=width, height=height,
                                     x=left, y=-bottom, advance_16=advance))
        start, end = missing[0], missing[-1]
        assert end - start < 65536 and len(pixels) < 1 << 20
        output.append(array(name + 'Bitmap', 'uint8_t', list(pixels)))
        output.append(array(name + 'Unicode', 'uint16_t', [cp - start for cp in missing]))
        output.append(f'static const Glyph {name}Glyphs[] = {{\n' + '\n'.join(
            '    {' + ','.join(str(value) for value in row) + '},' for row in records) + '\n};\n')
        output.append(f'static const Cmap {name}Cmap = {{{start},{end - start + 1},1,{name}Unicode,nullptr,{len(missing)},3,0}};\n')
        output.append(f'static const FontData {name}Data = {{{name}Bitmap,{name}Glyphs,&{name}Cmap,nullptr,0x08010000}};\n')
        output.append(f'static const Font {name}Fallback = {{0xa00e4864,0xa00e45aa,0,{size},{baseline},0x0001fe00,&{name}Data,nullptr,nullptr}};\n')
        output.append(f'static const Font {name}Font = {{0xa00e4864,0xa00e45aa,0,{size},{baseline},0x0001fe00,(const void *)0x{wrapper[6]:08x},&{name}Fallback,nullptr}};\n')
        assert all(cp in existing or cp in missing for cp in required)
        report[name.lower()] = dict(original=hex(address), weight=weight,
            line_height=size, baseline=baseline,
            original_descriptor=hex(wrapper[6]), preserved_original_glyphs=True,
            supplementary_count=len(missing), bitmap_bytes=len(pixels),
            supplementary_glyphs=glyph_report, coverage_complete=True)
    return '\n'.join(output), report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rom', type=Path, required=True)
    parser.add_argument('--font', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--report', type=Path)
    parser.add_argument('--check', action='store_true', help='Verify reproducibility without replacing the include')
    args = parser.parse_args()
    rom = args.rom.read_bytes()
    assert hashlib.sha256(rom).hexdigest() == ROM_SHA
    text, fonts = generate(rom, args.font)
    data = text.encode('utf-8')
    if args.check:
        assert args.output.read_bytes() == data, 'generated font differs'
    else:
        args.output.write_bytes(data)
    report = dict(passed=True, original_rom_sha256=ROM_SHA,
        source_font_sha256=hashlib.sha256(args.font.read_bytes()).hexdigest(),
        generated_sha256=hashlib.sha256(data).hexdigest(), generated_bytes=len(data),
        pillow_version=pillow_version, texts=TEXTS, fonts=fonts,
        check_mode=args.check, physical_rendering_verified=False)
    if args.report:
        args.report.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print('font coverage and reproducibility passed: ' + report['generated_sha256'])


if __name__ == '__main__':
    main()
